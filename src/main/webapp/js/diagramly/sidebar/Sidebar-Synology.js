	Sidebar.prototype.addSynologyNASPalette = function()
	{
		var imgDir = GRAPH_IMAGE_PATH;
		this.setCurrentSearchEntryLibrary('synology_nas');

		var items = [
			'f-RS3618xs_front',
			'f-RX1222sas_front',
			'RS2423RP+_front'
		];
		var titles = [
			'RS3618xs',
			'RX1222sas 扩展柜',
			'RS2423RP+'
		];
		var tags = {
			'f-RS3618xs_front': 'synology nas rack rs3618xs storage server',
			'f-RX1222sas_front': 'synology expansion unit rx1222sas',
			'RS2423RP+_front': 'synology nas rack rs2423 storage server'
		};

		var fns = [];
		for (var i = 0; i < items.length; i++)
		{
			fns.push(this.createVertexTemplateEntry(
				'image;html=1;image=' + imgDir + '/synology/' + items[i] + '.png',
				this.defaultImageWidth, this.defaultImageHeight,
				'', titles[i], titles[i] != null, null,
				this.filterTags(tags[items[i]])));
		}

		var prev = this.expandLibraries;
		this.expandLibraries = true;
		this.addPaletteFunctions('synology_nas', 'Synology NAS', true, fns);
		this.expandLibraries = prev;
		this.setCurrentSearchEntryLibrary();
	};

